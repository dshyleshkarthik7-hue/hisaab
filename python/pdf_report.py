"""Server-side bilingual PDF report with embedded Telugu-capable font."""
from __future__ import annotations
import io
import os
from datetime import datetime, timezone
from typing import Any

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.lib.colors import HexColor, black, white
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

# Prefer Hind Guntur (Telugu script support); fall back to Helvetica
_FONT_CANDIDATES = [
    "/app/fonts/HindGuntur-Regular.ttf",
    str(__import__('pathlib').Path(__file__).resolve().parent.parent / "fonts" / "HindGuntur-Regular.ttf"),
    "/usr/share/fonts/SlidesCarnival/google/Hind Guntur/HindGuntur-Regular.ttf",
    "/usr/share/fonts/SlidesCarnival/google/Hind Guntur/HindGuntur-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
]
_FONT_BOLD_CANDIDATES = [
    "/app/fonts/HindGuntur-Bold.ttf",
    str(__import__('pathlib').Path(__file__).resolve().parent.parent / "fonts" / "HindGuntur-Bold.ttf"),
    "/usr/share/fonts/SlidesCarnival/google/Hind Guntur/HindGuntur-Bold.ttf",
    "/usr/share/fonts/SlidesCarnival/google/Hind Guntur/HindGuntur-SemiBold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
]

FONT_NAME = "HisaabSans"
FONT_BOLD = "HisaabSans-Bold"
_FONT_PATH = None
_FONT_BOLD_PATH = None

for p in _FONT_CANDIDATES:
    if os.path.isfile(p):
        _FONT_PATH = p
        break
for p in _FONT_BOLD_CANDIDATES:
    if os.path.isfile(p):
        _FONT_BOLD_PATH = p
        break


def _register_fonts() -> None:
    if _FONT_PATH and FONT_NAME not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(FONT_NAME, _FONT_PATH))
    if _FONT_BOLD_PATH and FONT_BOLD not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(FONT_BOLD, _FONT_BOLD_PATH))
    elif _FONT_PATH and FONT_BOLD not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(FONT_BOLD, _FONT_PATH))


def _inr(n: float) -> str:
    try:
        return "₹" + f"{round(float(n)):,}"
    except Exception:
        return "₹—"


def _pct(n: float) -> str:
    try:
        return f"{float(n) * 100:.1f}%"
    except Exception:
        return "—"


def build_pdf(payload: dict[str, Any], lang: str = "en") -> bytes:
    """Build a bilingual PDF report. `lang` is 'en' or 'te'."""
    _register_fonts()
    te = lang == "te"

    L = {
        "title": "హిసాబ్ ఆర్థిక భవిష్యత్ నివేదిక" if te else "Hisaab Financial Future Report",
        "sub": "కుటుంబ ఆర్థిక సన్నివేశ విశ్లేషణ" if te else "Household-finance scenario analysis",
        "summary": "సారాంశం" if te else "Executive summary",
        "score": "అన్ని లక్ష్యాలు నెరవేరిన సన్నివేశాలు" if te else "Scenarios funding every goal",
        "corpus": "చివరి నిధి (మధ్యస్థం)" if te else "Ending corpus (median)",
        "depletion": "నిధి ఖాళీ అయ్యే సన్నివేశాలు" if te else "Scenarios with depleted corpus",
        "inputs": "మీరు అందించిన వివరాలు" if te else "Your inputs",
        "goals": "జీవిత లక్ష్యాలు" if te else "Life goals",
        "events": "జీవిత సంఘటనలు" if te else "Life events",
        "fan": "వార్షిక నిధి పరిధి" if te else "Annual corpus range",
        "assumptions": "నమూనా అంచనాలు" if te else "Model assumptions",
        "disclaimer": "ముఖ్య గమనిక" if te else "Important notice",
        "generated": "రూపొందించిన తేదీ" if te else "Generated",
        "year": "సంవత్సరం" if te else "Year",
        "name": "పేరు" if te else "Name",
        "cost": "ఖర్చు" if te else "Cost",
        "odds": "సాధ్యత" if te else "Odds",
        "note": (
            "ఈ నివేదిక Hisaab కుటుంబ ఆర్థిక సన్నివేశ సిమ్యులేటర్ ద్వారా రూపొందించబడింది. "
            "ఫలితాలు మీ ఇన్‌పుట్‌లు మరియు నమూనా అంచనాలపై ఆధారపడతాయి. "
            "Hisaab వ్యక్తిగతీకరించిన పెట్టుబడి సలహా ఇవ్వదు."
            if te else
            "This report is generated by the Hisaab household-finance scenario simulator. "
            "Results depend on your inputs and model assumptions. "
            "Hisaab does not provide personalised investment advice."
        ),
    }

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=16 * mm, rightMargin=16 * mm,
        topMargin=14 * mm, bottomMargin=14 * mm,
        title=L["title"], author="Hisaab",
    )

    styles = getSampleStyleSheet()
    body_font = FONT_NAME if _FONT_PATH else "Helvetica"
    bold_font = FONT_BOLD if (_FONT_BOLD_PATH or _FONT_PATH) else "Helvetica-Bold"

    s_title = ParagraphStyle("T", parent=styles["Title"], fontName=bold_font, fontSize=20,
                            textColor=HexColor("#174f40"), spaceAfter=4)
    s_sub = ParagraphStyle("S", parent=styles["Normal"], fontName=body_font, fontSize=10,
                          textColor=HexColor("#52636b"), spaceAfter=12)
    s_h = ParagraphStyle("H", parent=styles["Heading2"], fontName=bold_font, fontSize=13,
                        textColor=HexColor("#174f40"), spaceBefore=14, spaceAfter=6)
    s_p = ParagraphStyle("P", parent=styles["Normal"], fontName=body_font, fontSize=9,
                        leading=13, textColor=HexColor("#1c2d36"))
    s_small = ParagraphStyle("Sm", parent=s_p, fontSize=8, textColor=HexColor("#687780"))

    story = []
    story.append(Paragraph(L["title"], s_title))
    story.append(Paragraph(L["sub"], s_sub))
    story.append(HRFlowable(width="100%", thickness=1, color=HexColor("#d8e0dc"), spaceAfter=10))

    result = payload.get("result") or {}
    inputs = payload.get("inputs") or {}

    # Summary stats
    stats = [
        [L["score"], _pct(result.get("score", 0))],
        [L["corpus"], _inr((result.get("ending") or {}).get("p50", 0))],
        [L["depletion"], _pct(result.get("depletion_odds", 0))],
    ]
    t = Table(stats, colWidths=[110 * mm, 60 * mm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), body_font),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("FONTNAME", (1, 0), (1, -1), bold_font),
        ("TEXTCOLOR", (1, 0), (1, -1), HexColor("#28765d")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(Paragraph(L["summary"], s_h))
    story.append(t)

    # Inputs
    story.append(Paragraph(L["inputs"], s_h))
    rows = [
        ["Years", str(inputs.get("years", "—"))],
        ["Savings", _inr(inputs.get("savings", 0))],
        ["Monthly income", _inr(inputs.get("income", 0))],
        ["Monthly expense", _inr(inputs.get("expense", 0))],
        ["Monthly SIP", _inr(inputs.get("sip", 0))],
        ["Expected return", f"{inputs.get('ret', '—')}%"],
        ["Volatility", f"{inputs.get('vol', '—')}%"],
    ]
    it = Table(rows, colWidths=[80 * mm, 90 * mm])
    it.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), body_font),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 0), (-1, -1), HexColor("#f7f7f1")),
        ("GRID", (0, 0), (-1, -1), 0.3, HexColor("#dfe4df")),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(it)

    # Goals
    goals = result.get("goals") or inputs.get("goals") or []
    if goals:
        story.append(Paragraph(L["goals"], s_h))
        grow = [[L["name"], L["year"], L["cost"], L["odds"]]]
        for i, g in enumerate(goals):
            name = g.get("name", "—")
            at = g.get("at", "—")
            cost = g.get("cost", inputs.get("goals", [{}])[i].get("cost", 0) if isinstance(inputs.get("goals"), list) and i < len(inputs.get("goals") or []) else 0)
            odds = g.get("odds")
            grow.append([str(name), str(at), _inr(cost) if cost else "—", _pct(odds) if odds is not None else "—"])
        gt = Table(grow, colWidths=[55 * mm, 30 * mm, 45 * mm, 40 * mm])
        gt.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, 0), bold_font),
            ("FONTNAME", (0, 1), (-1, -1), body_font),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#e9e6d9")),
            ("GRID", (0, 0), (-1, -1), 0.3, HexColor("#dfe4df")),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(gt)

    # Fan chart table
    fan = result.get("fan") or []
    if fan:
        story.append(Paragraph(L["fan"], s_h))
        frows = [[L["year"], "10th", "Median", "90th"]]
        for i, row in enumerate(fan):
            frows.append([str(i), _inr(row.get("p10", 0)), _inr(row.get("p50", 0)), _inr(row.get("p90", 0))])
        ft = Table(frows, colWidths=[30 * mm, 45 * mm, 45 * mm, 45 * mm])
        ft.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, 0), bold_font),
            ("FONTNAME", (0, 1), (-1, -1), body_font),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#e9e6d9")),
            ("GRID", (0, 0), (-1, -1), 0.25, HexColor("#dfe4df")),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 2),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ]))
        story.append(ft)

    story.append(Paragraph(L["assumptions"], s_h))
    story.append(Paragraph(
        "Monthly cash-flow simulation · category-specific goal inflation · "
        "lognormal monthly returns · job-loss and medical-event assumptions · "
        "SIP capped by surplus after expenses."
        if not te else
        "నెలవారీ నగదు ప్రవాహ సిమ్యులేషన్ · వర్గాల వారీ లక్ష్య ద్రవ్యోల్బణం · "
        "లాగ్‌నార్మల్ నెలవారీ రాబడి · ఉద్యోగ విరామం మరియు వైద్య సంఘటనలు · "
        "SIP ఖర్చుల తర్వాత మిగులుకు పరిమితం.",
        s_p,
    ))

    story.append(Paragraph(L["disclaimer"], s_h))
    story.append(Paragraph(L["note"], s_p))
    story.append(Spacer(1, 8))
    story.append(Paragraph(
        f"{L['generated']}: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} · HISAAB · "
        f"Font: {'embedded Telugu-capable (Hind Guntur)' if _FONT_PATH else 'Helvetica fallback'}",
        s_small,
    ))

    doc.build(story)
    return buf.getvalue()
